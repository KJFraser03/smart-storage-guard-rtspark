import os
import numpy as np
import pandas as pd
from sklearn.neural_network import MLPClassifier
from sklearn.tree import DecisionTreeClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix

CLASS_NAMES = [
    "SAFE_STORAGE",
    "ENV_SPOILAGE_RISK",
    "LID_LEFT_OPEN",
    "TAMPER_OR_FALL"
]

def extract_features(df: pd.DataFrame) -> np.ndarray:
    """Compute the exact 6 engineered features used on the STM32F407 firmware."""
    acc_mag = np.sqrt(df["ax"]**2 + df["ay"]**2 + df["az"]**2)
    acc_dyn = np.abs(acc_mag - 0.95)
    gyro_mag = np.sqrt(df["gx"]**2 + df["gy"]**2 + df["gz"]**2)

    X = np.column_stack([
        df["temp_c"].values,
        df["humidity_pct"].values,
        df["als"].values,
        df["ps"].values,
        acc_dyn.values,
        gyro_mag.values
    ])
    return X.astype(np.float32)

def leakage_aware_temporal_split(df: pd.DataFrame, test_ratio: float = 0.25):
    """
    Contiguous block split per class with a 1-second (4-sample) guard gap
    so temporally correlated adjacent readings never leak across train/test sets.
    """
    train_idx, test_idx = [], []
    guard_samples = 4

    for cls in sorted(df["label"].unique()):
        cls_indices = df.index[df["label"] == cls].tolist()
        n = len(cls_indices)
        split_point = int(n * (1.0 - test_ratio))
        train_idx.extend(cls_indices[:max(1, split_point - guard_samples)])
        test_idx.extend(cls_indices[split_point:])

    return df.loc[train_idx], df.loc[test_idx]

def export_c_header(scaler: StandardScaler, mlp: MLPClassifier, out_path: str):
    """Export trained scaler & 6->12->4 MLP weights to C header for STM32F407."""
    W1 = mlp.coefs_[0].T       # shape (12, 6)
    B1 = mlp.intercepts_[0]    # shape (12,)
    W2 = mlp.coefs_[1].T       # shape (4, 12)
    B2 = mlp.intercepts_[1]    # shape (4,)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("#ifndef TRAINED_WEIGHTS_H\n#define TRAINED_WEIGHTS_H\n\n")
        f.write("/* Auto-generated by training/train_model.py from real RT-Spark board data */\n\n")

        def write_1d(name, arr):
            vals = ", ".join(f"{v:.6f}f" for v in arr)
            f.write(f"static const float {name}[{len(arr)}] = {{{vals}}};\n\n")

        def write_2d(name, mat):
            f.write(f"static const float {name}[{mat.shape[0]}][{mat.shape[1]}] = {{\n")
            for row in mat:
                vals = ", ".join(f"{v:.6f}f" for v in row)
                f.write(f"    {{{vals}}},\n")
            f.write("};\n\n")

        write_1d("FEAT_MEAN", scaler.mean_)
        write_1d("FEAT_SCALE", scaler.scale_)
        write_2d("W1", W1)
        write_1d("B1", B1)
        write_2d("W2", W2)
        write_1d("B2", B2)
        f.write("#endif /* TRAINED_WEIGHTS_H */\n")

def main():
    csv_path = os.path.join("dataset", "board_sensor_data.csv")
    if not os.path.exists(csv_path):
        print(f"[ERROR] {csv_path} not found. Record CSV data from Serial Monitor first!")
        return

    # Keep only valid numeric CSV rows (ignores any banner lines if copied accidentally)
    df = pd.read_csv(csv_path, on_bad_lines="skip")
    df = df[pd.to_numeric(df["label"], errors="coerce").notnull()].copy()
    df["label"] = df["label"].astype(int)
    for col in ["temp_c", "humidity_pct", "als", "ps", "ax", "ay", "az", "gx", "gy", "gz"]:
        df[col] = pd.to_numeric(df[col], errors="coerce")
    df = df.dropna().reset_index(drop=True)

    print(f"Loaded {len(df)} labeled samples across classes:\n{df['label'].value_counts().sort_index()}\n")

    train_df, test_df = leakage_aware_temporal_split(df, test_ratio=0.25)
    X_train, y_train = extract_features(train_df), train_df["label"].values
    X_test, y_test   = extract_features(test_df),  test_df["label"].values

    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s  = scaler.transform(X_test)

    # 1. Baseline Model: Shallow Decision Tree (Max Depth = 2)
    baseline = DecisionTreeClassifier(max_depth=2, random_state=42)
    baseline.fit(X_train_s, y_train)
    base_preds = baseline.predict(X_test_s)

    # 2. Target Edge AI Model: 6 -> 12 -> 4 ReLU MLP
    mlp = MLPClassifier(hidden_layer_sizes=(12,), activation="relu",
                        max_iter=1500, alpha=0.05, random_state=42)
    mlp.fit(X_train_s, y_train)
    mlp_preds = mlp.predict(X_test_s)

    print("=== BASELINE COMPARISON (Held-Out Leakage-Aware Test Set) ===")
    print(f"Baseline Decision Tree (depth=2) -> Accuracy: {accuracy_score(y_test, base_preds)*100:.2f}%, Macro-F1: {f1_score(y_test, base_preds, average='macro'):.4f}")
    print(f"Edge AI MLP (6->12->4)           -> Accuracy: {accuracy_score(y_test, mlp_preds)*100:.2f}%, Macro-F1: {f1_score(y_test, mlp_preds, average='macro'):.4f}\n")

    print("=== HELD-OUT MLP CLASSIFICATION REPORT ===")
    print(classification_report(y_test, mlp_preds, target_names=CLASS_NAMES, digits=4, zero_division=0))

    print("=== HELD-OUT CONFUSION MATRIX ===")
    print(confusion_matrix(y_test, mlp_preds))

    export_c_header(scaler, mlp, os.path.join("include", "trained_weights.h"))
    print("\n[SUCCESS] Exported trained weights to include/trained_weights.h")

if __name__ == "__main__":
    main()